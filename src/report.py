def _t(df: pd.DataFrame, cols: dict, fmt: dict | None = None) -> str:
    fmt = fmt or {}
    d = df[list(cols)].rename(columns=cols)
    lines = ["| " + " | ".join(d.columns) + " |", "|" + "---|" * len(d.columns)]
    for _, r in d.iterrows():
        cells = []
        for orig, c in cols.items():
            v = r[c]
            f = fmt.get(orig)
            if isinstance(v, (bool,)) or str(type(v)).endswith("bool_'>"):
                cells.append("yes" if v else "no")
            elif v is None or (not isinstance(v, str) and pd.isna(v)):
                cells.append("—")
            elif orig == "year":
                cells.append(str(int(v)))
            elif f:
                cells.append(f"{v:{f}}")
            else:
                cells.append(f"{v:,}" if isinstance(v, int) else str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


GS = {"accidents": "Accidents", "share_pct": "Share %", "fatal": "Fatal", "fatal_rate": "Fatality %",
      "ci_low": "CI low", "ci_high": "CI high", "casualties": "Casualties", "avg_casualties": "Avg cas.",
      "avg_risk": "Avg risk"}
GF = {"share_pct": ".1f", "fatal_rate": ".2f", "ci_low": ".1f", "ci_high": ".1f", "avg_casualties": ".2f",
      "avg_risk": ".3f", "accidents": ",", "fatal": ",", "casualties": ","}


def _gs(df, col, label, order=None):
    s = A.group_summary(df, col, order)
    t = A.fatal_rate_test(df, col)
    p = f"χ²({t['dof']}) = {t['statistic']:.2f}, p = {t['p_value']:.3f}, Cramér's V = {t['effect_size']:.3f}"
    return _t(s, {col: label, **GS}, GF) + f"\nFatality-rate test: {p}.\n"


def build(df: pd.DataFrame) -> str:
    k = A.kpis(df)
    out = ["# Exploratory Data Analysis — Findings\n",
           "_Generated by `python -m src.report` from all "
           f"{k['accidents']:,} records of the cleaned dataset. No sampling._\n",
           "> **Provenance caveat.** Statistical fingerprints (uniform marginals, an exact formula for "
           "`risk_score`, generation rules linking casualties to vehicles) show the data is simulated. "
           "Results describe this dataset, not Indian road safety.\n",
           "Terminology: *accidents* = records; *fatal accidents* = records with severity 'fatal'; "
           "*fatality rate* = fatal accidents ÷ accidents in the same group; *casualties* = persons killed or "
           "injured (deaths are not recorded separately, so fatalities cannot be counted).\n"]

    out.append("\n## A. Overall\n")
    out.append(f"- Accidents: **{k['accidents']:,}** over {k['days']:,} days "
               f"({df['date'].min():%d %b %Y} – {df['date'].max():%d %b %Y})\n"
               f"- Casualties: **{k['casualties']:,}** (avg {k['avg_casualties']:.3f} per accident; "
               f"{k['casualties_in_fatal']:,} in fatal accidents)\n"
               f"- Fatal / major / minor: **{k['fatal']:,} / {k['major']:,} / {k['minor']:,}** "
               f"({k['fatal_pct']:.2f}% / {k['major'] / k['accidents'] * 100:.2f}% / {k['minor'] / k['accidents'] * 100:.2f}%)\n"
               f"- Average vehicles involved: {k['avg_vehicles']:.3f}; average risk score {k['avg_risk']:.4f}\n")
    yt = A.yearly_trend(df)
    out.append("\n**Year-wise trend** (accidents per day handles the partial 2025):\n\n")
    out.append(_t(yt, {"year": "Year", "accidents": "Accidents", "days_observed": "Days", "accidents_per_day": "Per day",
                       "change_in_daily_rate_pct": "Δ per-day %", "fatal_rate": "Fatality %", "is_partial": "Partial"},
                  {"accidents_per_day": ".2f", "change_in_daily_rate_pct": "+.2f", "fatal_rate": ".2f", "accidents": ","}))
    sp = A.same_period_comparison(df)
    out.append(f"\nSame-window comparison ({sp['window'].iloc[0]}):\n\n")
    out.append(_t(sp, {"year": "Year", "accidents": "Accidents", "change_pct": "Δ %", "fatal_rate": "Fatality %"},
                  {"change_pct": "+.2f", "fatal_rate": ".2f", "accidents": ","}))

    out.append("\n## B. Geography\n\n### By state\n\n" + _gs(df, "state", "State"))
    out.append("\n### By city\n\n" + _gs(df, "city", "City"))
    out.append("\nCoordinates: all records fall inside India and within "
               f"{df['km_from_city_centre'].max():.1f} km of their city's median point "
               f"(median {df['km_from_city_centre'].median():.1f} km).\n")

    out.append("\n## C. Temporal\n\n### Time of day (per clock-hour)\n\n")
    out.append(_t(A.per_slot_rate(df), {"time_of_day": "Time of day", "accidents": "Accidents",
                                        "hours_in_bucket": "Hours", "accidents_per_hour": "Per hour",
                                        "fatal_rate": "Fatality %"},
                  {"accidents_per_hour": ".1f", "fatal_rate": ".2f", "accidents": ","}))
    out.append("\n### Weekday vs weekend (per calendar day)\n\n")
    out.append(_t(A.weekday_weekend(df), {"day_type": "Day type", "accidents": "Accidents", "calendar_days": "Days",
                                          "accidents_per_day": "Per day", "fatal_rate": "Fatality %",
                                          "avg_casualties": "Avg cas."},
                  {"accidents_per_day": ".2f", "fatal_rate": ".2f", "avg_casualties": ".3f", "accidents": ","}))
    out.append("\n### Peak vs off-peak\n\n" + _gs(df, "peak_label", "Period"))
    out.append("\n### Day of week\n\n" + _gs(df, "day_of_week", "Day", config.DAY_ORDER))
    out.append("\n### Season (IMD)\n\n" + _gs(df, "season", "Season", config.SEASON_ORDER))

    out.append("\n## D. Severity\n")
    for col, lab, order in [("road_type", "Road type", None), ("weather", "Weather", None),
                            ("traffic_density", "Density", config.LEVEL_ORDER),
                            ("time_of_day", "Time of day", config.TIME_OF_DAY_ORDER),
                            ("vehicles_involved", "Vehicles", None)]:
        out.append(f"\n### Severity by {lab.lower()}\n\n" + _gs(df, col, lab, order))
    cs = df.groupby("accident_severity")["casualties"].agg(["count", "sum", "mean"]).reindex(config.SEVERITY_ORDER)
    out.append("\n### Casualties by severity\n\n| Severity | Accidents | Casualties | Avg |\n|---|---|---|---|\n" +
               "\n".join(f"| {s} | {int(r['count']):,} | {int(r['sum']):,} | {r['mean']:.3f} |" for s, r in cs.iterrows()) + "\n")
    out.append(f"\n{int(df['dq_major_zero_casualties'].sum()):,} major accidents have zero casualties; every fatal "
               "accident has casualties equal to vehicles involved.\n")

    out.append("\n## E. Causes\n\n" + _gs(df, "cause", "Cause"))
    out.append("\n## F. Weather and visibility\n\n" + _gs(df, "weather", "Weather"))
    out.append("\n" + _gs(df, "visibility", "Visibility", config.LEVEL_ORDER))
    out.append("\nVisibility is a function of weather (clear → high; fog → low; rain → low or medium), so the two "
               "are not independent factors.\n\n### Temperature bands\n\n")
    out.append(_t(A.temperature_bands(df), {"temp_band": "Band", **GS}, GF))

    out.append("\n## G. Road infrastructure\n\n" + _gs(df, "lanes", "Lanes"))
    out.append("\n" + _gs(df, "signal_label", "Signal"))

    out.append("\n## H. Festivals\n\n" + _gs(df, "festival_name", "Festival"))
    fs = A.group_summary(df[df["festival_flag"] == 1], "festival_name")
    base = df.loc[df["festival_flag"] == 0, "is_fatal"].astype(float).mean()
    from scipy import stats
    notable = [f"{r.festival_name} ({int(r.fatal)}/{int(r.accidents)}, exact binomial p = "
               f"{stats.binomtest(int(r.fatal), int(r.accidents), base).pvalue:.3f})"
               for r in fs.itertuples() if stats.binomtest(int(r.fatal), int(r.accidents), base).pvalue < config.ALPHA]
    dates = df[df["festival_flag"] == 1].groupby("festival_name")["date"].nunique()
    out.append(f"\nFestival groups hold {int(fs['accidents'].min())}–{int(fs['accidents'].max())} records each, drawn "
               f"from {int(dates.min())}–{int(dates.max())} distinct dates. "
               + (f"Rates departing from the non-festival baseline ({base * 100:.1f}%): {', '.join(notable)} — "
                  "with so few records and dates this is not a reliable festival effect. " if notable else
                  "No festival's rate departs significantly from the non-festival baseline. ")
               + "Labels exist only for some festival dates (see the data profile).\n")

    out.append("\n## I. Risk score\n\n" + f"`{RISK_FORMULA_TEXT}` reproduces the column exactly.\n\n")
    rs = df.groupby("accident_severity")[["risk_score", "condition_risk"]].mean().reindex(config.SEVERITY_ORDER)
    out.append("| Severity | Mean risk | Mean condition risk |\n|---|---|---|\n" +
               "\n".join(f"| {s} | {r['risk_score']:.3f} | {r['condition_risk']:.3f} |" for s, r in rs.iterrows()) + "\n")
    rp = A.risk_profiles(df, ["road_type", "weather", "time_of_day", "traffic_density"], min_n=50, top=8)
    out.append(f"\nTop observed profiles (≥50 accidents; {int(rp['combinations_tested'].iloc[0])} combinations tested; "
               f"{int(rp['significant_after_correction'].sum())} significant after FDR correction):\n\n")
    out.append(_t(rp, {"road_type": "Road", "weather": "Weather", "time_of_day": "Time", "traffic_density": "Density",
                       "accidents": "Accidents", "fatal_rate": "Fatality %", "ci_low": "CI low", "ci_high": "CI high",
                       "p_adjusted": "p (FDR)"},
                  {"fatal_rate": ".1f", "ci_low": ".1f", "ci_high": ".1f", "p_adjusted": ".3f"}))

    out.append("\n## J. Statistical tests (Benjamini–Hochberg adjusted)\n\n")
    tb = A.test_battery(df)
    out.append(_t(tb, {"test": "Test", "statistic": "Stat", "p_value": "p", "p_adjusted": "p (FDR)",
                       "effect_name": "Effect", "effect_size": "Size", "interpretation": "Interpretation"},
                  {"statistic": ".2f", "p_value": ".4f", "p_adjusted": ".4f", "effect_size": ".3f"}))
    corr = A.correlation_matrix(df)
    pairs = corr.where(~pd.DataFrame(
        [[i >= j for j in range(len(corr))] for i in range(len(corr))], index=corr.index, columns=corr.columns)
    ).stack().sort_values(key=abs, ascending=False).head(8)
    out.append("\n**Strongest Spearman correlations:** " +
               "; ".join(f"{a} – {b}: {v:+.2f}" for (a, b), v in pairs.items()) +
               ". Each reflects a construction rule (casualties ≤ vehicles; risk formula; peak-hour definition), "
               "not a behavioural relationship.\n")
    out.append("\n### Outliers\n\n" + _t(A.outlier_summary(df), {"variable": "Variable", "lower_fence": "Lower",
                                                                 "upper_fence": "Upper", "iqr_outliers": "IQR outliers",
                                                                 "z_gt_3": "|z|>3", "min": "Min", "max": "Max"},
                                         {"lower_fence": ".2f", "upper_fence": ".2f"}))

    out.append("\n## Automatically generated insights (full dataset)\n\n")
    for i in generate_insights(df):
        out.append(f"- **{i['title']} — {i['value']}** [{i['status'].replace('_', ' ')}]. {i['detail']}\n")
    return "".join(out)


def main():
    df = ensure_clean_data()
    path = config.REPORTS_DIR / "eda_findings.md"
    path.write_text(build(df))
    print(f"EDA findings written → {path}")


if __name__ == "__main__":
    main()
